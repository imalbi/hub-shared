const shown = 5;
const escapeMarkup = (text: string) => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');

export function notification(titles: ReadonlyArray<{ title: string; company: string }>) {
  const count = titles.length;
  const lines = titles.slice(0, shown).map((posting) => escapeMarkup(`${posting.title} (${posting.company})`));
  if (count > shown) lines.push(`e altre ${count - shown}`);
  return {
    title: count === 1 ? 'Lavoro: 1 nuova offerta' : `Lavoro: ${count} nuove offerte`,
    body: lines.join('\n'),
  };
}

const dayFormat = new Intl.DateTimeFormat('it-IT', { day: 'numeric', month: 'short' });

/** "Sviluppatore backend, 3 ott, in attesa": the role, the day and the status of an earlier application. */
export function companyApplicationLine(app: { title: string; appliedAt: number; status: keyof typeof statusLabels }) {
  return `${app.title}, ${dayFormat.format(app.appliedAt)}, ${statusLabels[app.status].toLowerCase()}`;
}

